"""Small shared storage boundary for the hackathon demo. Integration-owned."""

from typing import Protocol


class NotFound(LookupError):
    """Unknown record, or a record outside the requested run/disaster."""


class Conflict(ValueError):
    """Invalid state transition or conflicting reuse of an idempotency key."""


class InvalidInput(ValueError):
    """Malformed demo input."""


class RecoveryStore(Protocol):
    def list_disasters(self) -> list[dict]: ...
    def list_organizations(self) -> list[dict]: ...
    def get_board(self, run_id: str) -> dict: ...
    def create_request(self, run_id: str, payload: dict) -> dict: ...
    def claim_request(self, run_id: str, request_id: str, payload: dict) -> dict: ...
    def report_delivery(self, run_id: str, request_id: str, payload: dict) -> dict: ...
    def verify_request(self, run_id: str, request_id: str, payload: dict) -> dict: ...
    def save_call(self, run_id: str, payload: dict) -> dict: ...
    def save_lesson(self, run_id: str, payload: dict) -> dict: ...
    def approve_lesson(self, run_id: str, lesson_id: str, payload: dict) -> dict: ...
    def save_evaluation(self, run_id: str, payload: dict) -> dict: ...
    def emit_event(self, run_id: str, payload: dict) -> dict: ...
