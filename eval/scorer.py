"""Deterministic evaluator: scores one run's output against hand-labelled ground truth.

Pure functions over plain dicts and lists; no DB access. Shapes follow `schemas.py` and run
isolation follows `interfaces.py`. Proposals and probe answers are generated by a run, so only
the scored run's own count. Contacts are events, so this scenario's inputs (run_id "scenario")
count as well. Documents with no run_id belong to no run and never count.

Times are simulated hours since day 0. `to_days` and `to_hours` are the only place hours and
days are converted. "Before" always means strictly earlier.

Ground truth is `schemas.Needle`, `schemas.Decoy`, `schemas.RegistryEntry` and
`schemas.TruthPromise` (status "kept" at status_ts means the promise was kept then). Probe answers
are `schemas.PromiseProbe`. Contacts are `schemas.Event`s showing the household was heard from;
the caller picks which sources count.
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable, Iterable

from interfaces import event_visible_to_run
from schemas import SCENARIO_RUN_ID

HOURS_PER_DAY = 24
# An escalation catches a needle only if it cites at least this many of the needle's events.
MIN_CITED = 2
SILENT_AFTER_DAYS = 3
# Every system is asked for each household's open promises at this interval.
PROBE_EVERY_DAYS = 3
# Lower edges, in days, of the promise-age buckets. The last bucket is open-ended.
AGE_BUCKET_EDGES_DAYS = (0, 1, 3, 7, 14)


def to_days(hours: float) -> float:
    return hours / HOURS_PER_DAY


def to_hours(days: float) -> float:
    return days * HOURS_PER_DAY


def probe_times(as_of: float) -> list[float]:
    """Probe checkpoints up to `as_of`. Fixed here, so no system can skip an awkward one."""
    step = to_hours(PROBE_EVERY_DAYS)
    return [step * n for n in range(1, int(as_of // step) + 1)]


def for_run(docs: Iterable[dict], run_id: str) -> list[dict]:
    """Documents the run generated itself. Unstamped documents belong to no run and are dropped."""
    return [doc for doc in docs if doc.get("run_id") == run_id]


def _ratio(part: int, whole: int) -> float | None:
    return part / whole if whole else None


def _cited(proposal: dict) -> set[str]:
    return set(proposal.get("cited_event_ids") or ())


def score_needle(needle: dict, proposals: list[dict]) -> dict:
    """Catch and impact result for one needle. `proposals` must already be filtered to one run.

    The required event ids identify the needle, so the proposal's household_id is not compared with
    the truth id: a household the runtime filed itself carries its own id, never W5's hidden one.
    """
    required = set(needle["required_event_ids"])
    if len(required) < MIN_CITED:
        raise ValueError(f"needle {needle['needle_id']!r} lists fewer than {MIN_CITED} required events")
    catches = [p["ts"] for p in proposals
               if p["ts"] < needle["deadline"] and len(_cited(p) & required) >= MIN_CITED]
    result = {"needle_id": needle["needle_id"], "kind": needle["kind"], "caught": bool(catches),
              "escalated_at": None, "reached_in_time": False, "warning_days": None}
    if catches:
        escalated_at = min(catches)
        result["escalated_at"] = escalated_at
        result["reached_in_time"] = escalated_at + needle["response_hours"] < needle["danger_at"]
        result["warning_days"] = to_days(needle["danger_at"] - escalated_at)
    return result


def false_escalations(decoys: list[dict], proposals: list[dict]) -> dict:
    """Each proposal citing any decoy event is one false escalation, however many it cites."""
    decoy_of = {event_id: decoy["decoy_id"] for decoy in decoys for event_id in decoy["event_ids"]}
    count, triggered = 0, set()
    for proposal in proposals:
        hit = {decoy_of[event_id] for event_id in _cited(proposal) if event_id in decoy_of}
        count += bool(hit)
        triggered |= hit
    return {"count": count, "decoy_ids": sorted(triggered)}


def _on_time(promise: dict, proposals: list[dict]) -> bool:
    """Kept, or escalated by a proposal citing its source event, before it fell due."""
    if promise.get("status") == "kept" and promise["status_ts"] < promise["due_ts"]:
        return True
    return any(p.get("household_id") == promise["household_id"]
               and p["ts"] < promise["due_ts"]
               and promise["source_event_id"] in _cited(p) for p in proposals)


def silent_households(registry: list[dict], contacts: list[dict], as_of: float) -> list[str]:
    """Opted-in households not heard from for more than SILENT_AFTER_DAYS at `as_of`.

    `contacts` must already be limited to what the run may see. A household never heard from
    has been silent since hour 0. Contacts after `as_of` have not happened yet and are ignored.
    """
    last_heard: dict[str, float] = {}
    for contact in contacts:
        household = contact.get("household_id")
        if household and contact["ts"] <= as_of:
            last_heard[household] = max(contact["ts"], last_heard.get(household, contact["ts"]))
    limit = to_hours(SILENT_AFTER_DAYS)
    return sorted({entry["household_id"] for entry in registry
                   if entry.get("opt_in") is True
                   and as_of - last_heard.get(entry["household_id"], 0) > limit})


def _open_at(promise: dict, ts: float) -> bool:
    """Open as `schemas.Promise` means it: made, not yet due, not yet kept."""
    kept = promise.get("status") == "kept" and promise["status_ts"] <= ts
    return promise["made_ts"] <= ts < promise["due_ts"] and not kept


def promise_recall_by_age(promises: list[dict], probes: list[dict], as_of: float) -> dict:
    """Share of open promises the run named when probed, bucketed by the promise's age then.

    `probes` must already be filtered to one run. Answers at times off the probe schedule are
    ignored. A household with no answer named nothing. Named events that were not an open
    promise of that household at that probe are counted in `named_not_open`.
    """
    schedule = probe_times(as_of)
    named: dict[tuple[float, str], set[str]] = {}
    for probe in probes:
        if probe["probe_ts"] in schedule:
            named.setdefault((probe["probe_ts"], probe["household_id"]), set()).update(probe["source_event_ids"])
    edges = AGE_BUCKET_EDGES_DAYS
    buckets = [{"label": f"{lo}-{hi}d" if hi is not None else f"{lo}d+", "min_days": lo, "max_days": hi,
                "open": 0, "recalled": 0, "recall": None}
               for lo, hi in zip(edges, (*edges[1:], None), strict=True)]
    open_now: dict[tuple[float, str], set[str]] = {}
    for ts in schedule:
        for promise in promises:
            if not _open_at(promise, ts):
                continue
            key = (ts, promise["household_id"])
            open_now.setdefault(key, set()).add(promise["source_event_id"])
            age_days = to_days(ts - promise["made_ts"])
            bucket = next(b for b in reversed(buckets) if age_days >= b["min_days"])
            bucket["open"] += 1
            bucket["recalled"] += int(promise["source_event_id"] in named.get(key, ()))
    for bucket in buckets:
        bucket["recall"] = _ratio(bucket["recalled"], bucket["open"])
    total = sum(bucket["open"] for bucket in buckets)
    recalled = sum(bucket["recalled"] for bucket in buckets)
    return {"probe_times": schedule, "open": total, "recalled": recalled,
            "recall": _ratio(recalled, total),
            "named_not_open": sum(len(ids - open_now.get(key, set())) for key, ids in named.items()),
            "by_age": buckets}


def score_run(run_id: str, *, scenario_id: str, proposals: list[dict], needles: list[dict],
              decoys: list[dict], promises: list[dict], registry: list[dict], contacts: list[dict],
              probes: list[dict], as_of: float, emit: Callable[[dict], None] | None = None) -> dict:
    """Score one run at simulated time `as_of`. Same inputs, same score.

    `needle_recall`, `impact` and `goal` match `schemas.Score`; `promise_recall` and `detail` are
    extra. A ratio with nothing to divide by is None, not 0. `emit`, when given, receives one
    `system_event` with a deterministic `_id`, so re-scoring the same run does not duplicate it.
    """
    if not run_id or run_id == SCENARIO_RUN_ID:
        raise ValueError("score a run by its own run_id, not the shared scenario")
    run_proposals = for_run(proposals, run_id)
    results = [score_needle(needle, run_proposals) for needle in needles]
    caught = [result for result in results if result["caught"]]
    reached = [needle for needle, result in zip(needles, results, strict=True) if result["reached_in_time"]]
    warning = [result["warning_days"] for result in caught]
    false = false_escalations(decoys, run_proposals)
    due = [promise for promise in promises if promise["due_ts"] <= as_of]
    on_time = sum(_on_time(promise, run_proposals) for promise in due)
    visible = [event for event in contacts if event_visible_to_run(event, run_id, scenario_id)]
    silent = silent_households(registry, visible, as_of)
    score = {
        "run_id": run_id,
        "scenario_id": scenario_id,
        "as_of": as_of,
        "needle_recall": _ratio(len(caught), len(results)),
        "impact": {"households_reached_in_time": len({needle["household_id"] for needle in reached}),
                   "people_reached_in_time": sum(needle["people_at_risk"] for needle in reached),
                   "days_warning_gained": sum(warning) / len(warning) if warning else None,
                   "false_escalations": false["count"]},
        "goal": {"promises_on_time_pct": 100 * on_time / len(due) if due else None,
                 "silent_households": len(silent)},
        "promise_recall": promise_recall_by_age(promises, for_run(probes, run_id), as_of),
        "detail": {"needles": results, "false_escalation_decoy_ids": false["decoy_ids"],
                   "promises_due": len(due), "promises_on_time": on_time,
                   "silent_household_ids": silent},
    }
    if emit is not None:
        digest = hashlib.sha256(f"{run_id}|eval|run_scored|{as_of}".encode()).hexdigest()[:16]
        emit({"_id": f"sev-{digest}", "run_id": run_id, "module": "eval", "action": "run_scored",
              "ts": as_of, "needle_recall": score["needle_recall"], "false_escalations": false["count"]})
    return score
